#!/usr/bin/env python3
"""Generate block-XOR native string tables from SV_STR/SV_WSTR calls."""

import hashlib
import pathlib
import re
import sys
import time

CALL = re.compile(
    r"SV_(W?STR)\(\s*(SV_[A-F0-9]{16})\s*,\s*(L?\"(?:\\.|[^\"\\])*\")\s*\)"
)
RENAMED_CLASSES = pathlib.Path(__file__).with_name("renamed_classes.txt")


def load_renamed_classes() -> dict[str, str]:
    renamed: dict[str, str] = {}
    if not RENAMED_CLASSES.exists():
        return renamed
    for line in RENAMED_CLASSES.read_text(encoding="utf-8").splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            renamed[parts[0]] = parts[1]
    return renamed


def key4(seed: int, build_time: str) -> int:
    """FNV-style key schedule used by Refactored-Xor-String."""
    value = seed & 0xFFFFFFFF
    for char in build_time:
        value = ((value ^ ord(char)) * 16777619) & 0xFFFFFFFF
    return value


def key8(block_index: int, build_time: str) -> int:
    first = key4(2166136261 + block_index, build_time)
    second = key4(first, build_time)
    return ((first << 32) | second) & 0xFFFFFFFFFFFFFFFF


def encrypt_blocks(data: bytes, build_time: str) -> tuple[list[int], list[int]]:
    block_count = max(1, (len(data) + 7) // 8)
    padded = data + bytes(block_count * 8 - len(data))
    cipher: list[int] = []
    keys: list[int] = []
    for index in range(block_count):
        plain = int.from_bytes(padded[index * 8 : index * 8 + 8], "little")
        key = key8(index, build_time)
        cipher.append((~(plain ^ key)) & 0xFFFFFFFFFFFFFFFF)
        keys.append(key)
    return cipher, keys


def parse_literal(token: str) -> str:
    body = token[2:-1] if token.startswith("L") else token[1:-1]
    simple = {
        "a": "\a", "b": "\b", "f": "\f", "n": "\n",
        "r": "\r", "t": "\t", "v": "\v", "\\": "\\",
        "'": "'", '"': '"', "?": "?",
    }
    decoded: list[str] = []
    index = 0
    while index < len(body):
        if body[index] != "\\":
            decoded.append(body[index])
            index += 1
            continue
        index += 1
        if index >= len(body):
            raise ValueError("unterminated escape in string literal")
        escape = body[index]
        if escape in simple:
            decoded.append(simple[escape])
            index += 1
        elif escape in "01234567":
            end = index + 1
            while end < len(body) and end < index + 3 and body[end] in "01234567":
                end += 1
            decoded.append(chr(int(body[index:end], 8)))
            index = end
        elif escape == "x":
            end = index + 1
            while end < len(body) and body[end] in "0123456789abcdefABCDEF":
                end += 1
            if end == index + 1:
                raise ValueError("empty hexadecimal escape in string literal")
            decoded.append(chr(int(body[index + 1:end], 16)))
            index = end
        elif escape in "uU":
            digits = 4 if escape == "u" else 8
            end = index + 1 + digits
            decoded.append(chr(int(body[index + 1:end], 16)))
            index = end
        elif escape == "\n":
            index += 1
        elif escape == "\r" and index + 1 < len(body) and body[index + 1] == "\n":
            index += 2
        else:
            decoded.append(escape)
            index += 1
    return "".join(decoded)


def expected_id(kind: str, literal_token: str) -> str:
    digest = hashlib.sha256(
        f"{kind}:{literal_token}".encode("utf-8")
    ).hexdigest()[:16]
    return "SV_" + digest.upper()


def uint64_array(values: list[int]) -> str:
    return "{" + ", ".join(
        f"UINT64_C(0x{value:016X})" for value in values
    ) + "}"


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: gen_obf.py OUTPUT SOURCE...", file=sys.stderr)
        return 2
    output = pathlib.Path(sys.argv[1])
    build_time = time.strftime("%H:%M:%S", time.gmtime())
    renamed_classes = load_renamed_classes()
    entries: dict[tuple[str, str], str] = {}
    for source_name in sys.argv[2:]:
        source = pathlib.Path(source_name)
        text = source.read_text(encoding="utf-8")
        for match in CALL.finditer(text):
            kind = "WSTR" if match.group(1) == "WSTR" else "STR"
            identifier = match.group(2)
            literal_token = match.group(3)
            plain = parse_literal(literal_token)
            wanted = expected_id(kind, literal_token)
            if identifier != wanted:
                raise SystemExit(
                    f"{source}: stale string id {identifier}; expected {wanted}"
                )
            plain = renamed_classes.get(plain, plain)
            entries[(kind, identifier)] = plain

    lines = [
        "/* AUTO-GENERATED by gen_obf.py. DO NOT EDIT. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for (kind, identifier), plain in sorted(entries.items()):
        raw = plain.encode("utf-16le" if kind == "WSTR" else "utf-8")
        cipher, keys = encrypt_blocks(raw, build_time)
        prefix = f"SV_{kind}_{identifier}"
        lines.extend(
            [
                f"static const uint64_t {prefix}_DATA[{len(cipher)}] = "
                f"{uint64_array(cipher)};",
                f"static const uint64_t {prefix}_KEYS[{len(keys)}] = "
                f"{uint64_array(keys)};",
                f"#define {prefix}_BLOCKS {len(cipher)}",
                f"#define {prefix}_LEN {len(raw)}",
                "",
            ]
        )
    lines.extend(
        [
            "#define SV_STR(identifier, plaintext) \\",
            "    sonyvegas_obf_dec(SV_STR_##identifier##_DATA, \\",
            "            SV_STR_##identifier##_KEYS, \\",
            "            SV_STR_##identifier##_BLOCKS, SV_STR_##identifier##_LEN)",
            "#define SV_WSTR(identifier, plaintext) \\",
            "    sonyvegas_obf_dec_wide(SV_WSTR_##identifier##_DATA, \\",
            "            SV_WSTR_##identifier##_KEYS, \\",
            "            SV_WSTR_##identifier##_BLOCKS, SV_WSTR_##identifier##_LEN)",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"generated {output} with {len(entries)} encrypted strings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
